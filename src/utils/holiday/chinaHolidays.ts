/**
 * 内置年表已收录的年份。用于判断某年是否有权威数据。
 */
export const BUILTIN_HOLIDAY_YEARS: number[] = [2025, 2026, 2027];

/**
 * 查询内置法定年表中的特定日期信息
 */
export function getBuiltinChinaHoliday(dateStr: string): { type: "休" | "班"; name: string } | null {
  return BUILTIN_CHINA_HOLIDAYS[dateStr] || null;
}

/**
 * 判断某个年份是否已有内置权威年表。
 * 没有年表的年份只显示周末「休」，不臆造调休安排。
 */
export function hasBuiltinYear(year: number): boolean {
  return BUILTIN_HOLIDAY_YEARS.includes(year);
}
